#!/usr/bin/env python3
"""Generates the FE8 event command table from the decomp's include/eventscript.h.

usage: tools/gen_fe8_event_commands.py <fireemblem8u checkout> > tools/extract/src/main/kotlin/gbafe/extract/fe8/events/Fe8EventCommands.kt

Every `#define Evt...(...)` built from exactly one `_EvtArg0`/`_EvtAutoCmdLen*` gives one row keyed by the
encoded header (cmd, len, sub); the first macro per key wins (aliases are listed after it). Names are the
macro names without the `Evt`/`Event` prefix, in snake_case.
"""
import re
import sys
from pathlib import Path


def snake(name):
    name = re.sub(r"^(Evt|Event)", "", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return name.lower()


def main(decomp):
    src = (Path(decomp) / "include/eventscript.h").read_text()
    joined = re.sub(r"\\\n", " ", src)
    consts = {}
    for m in re.finditer(r"\b(EV_CMD_\w+|EVT?SUBCMD_\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)", src):
        consts[m.group(1)] = int(m.group(2), 0)

    def val(tok):
        tok = tok.strip()
        if tok in consts:
            return consts[tok]
        m = re.fullmatch(r"(\w+)\s*-\s*(0x[0-9A-Fa-f]+|\d+)", tok)
        if m and m.group(1) in consts:
            return consts[m.group(1)] - int(m.group(2), 0)
        return int(tok, 0)

    rows = {}
    for line in joined.splitlines():
        m = re.match(r"#define\s+(Evt\w+|Event\w+)(\([^)]*\))?\s+(.*)", line)
        if not m:
            continue
        name, params, body = m.group(1), (m.group(2) or "()")[1:-1], m.group(3)
        calls = re.findall(r"_EvtArg0\(\s*([^,]+),\s*([^,]+),\s*([^,]+),", body) + \
            [(c, n, "0") for n, c in re.findall(r"_EvtAutoCmdLen(\d)\(\s*([^)]+)\)", body)]
        if len(calls) != 1:
            continue
        cmd, ln, sub = calls[0]
        args = [p.strip() for p in params.split(",") if p.strip()]
        # A sub-command may embed a 1-bit macro parameter (EvtMoveUnit's `modify`): one row per value, the
        # parameter's name appended to the command name for value 1.
        inner = [a for a in args if re.search(r"\b%s\b" % re.escape(a), sub)]
        for bits in range(1 << len(inner)):
            env = dict(consts, true=1, false=0)
            env.update({a: (bits >> i) & 1 for i, a in enumerate(inner)})
            try:
                key = (val(cmd), val(ln), eval(sub, {}, env) & 0xF)
            except (ValueError, NameError, SyntaxError):
                break
            suffix = "".join("_" + a for i, a in enumerate(inner) if (bits >> i) & 1)
            rows.setdefault(key, []).append((name, [a for a in args if a not in inner], suffix))

    out = []
    out.append("package gbafe.extract.fe8.events\n")
    out.append("// GENERATED by tools/gen_fe8_event_commands.py from fireemblem8u include/eventscript.h. Do not edit.\n")
    out.append("/** FE8 event commands keyed by header `(cmd shl 8) or (len shl 4) or sub`. */")
    out.append("public object Fe8EventCommands {")
    out.append("    /** One command form: [name] (snake_case macro name), decomp [macro], its [params] and aliases. */")
    out.append("    public class Command(")
    out.append("        /** `.fe8s` command name. */")
    out.append("        public val name: String,")
    out.append("        /** Decomp macro it comes from. */")
    out.append("        public val macro: String,")
    out.append("        /** The macro's parameter names. */")
    out.append("        public val params: List<String>,")
    out.append("        /** Other macros encoding the same header. */")
    out.append("        public val aliases: List<String>,")
    out.append("    )\n")
    out.append("    /** Header word → command. */")
    out.append("    public val byHeader: Map<Int, Command> = mapOf(")
    for (cmd, ln, sub), forms in sorted(rows.items()):
        name, args, suffix = forms[0]
        al = ", ".join('"%s"' % a for a, _, _ in forms[1:])
        ps = ", ".join('"%s"' % a for a in args)
        out.append('        0x%04X to Command("%s", "%s", listOf(%s), listOf(%s)),' % ((cmd << 8) | (ln << 4) | sub, snake(name) + suffix, name, ps, al))
    out.append("    )")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
