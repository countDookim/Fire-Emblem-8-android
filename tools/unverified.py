#!/usr/bin/env python3
"""List every `Transcribed from <file>: <Func>` KDoc entry (written but unverified decomp code).

Scans main-source Kotlin (same source sets as tools/progress.py), parses each entry including a
reason that wraps over following comment lines, and generates docs/plans/UNVERIFIED.md.
Every entry must carry `(not verified: <reason>)`; --check fails on drift or a missing reason.

  python3 tools/unverified.py --write   regenerate docs/plans/UNVERIFIED.md
  python3 tools/unverified.py --check   fail (exit 1) if it is stale or a reason is missing
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import progress  # noqa: E402

ROOT = progress.ROOT
OUT = "docs/plans/UNVERIFIED.md"
TRANSCRIBED_RX = re.compile(r"Transcribed from ((?:src|asm)/[\w./-]+): ([\w, ]+)")
MARKER_RX = re.compile(r"(?:Transcribed|Ported) from (?:src|asm)/")
REASON_RX = re.compile(r"not verified:\s*")
HEADER = """\
# Unverified transcriptions

<!-- Generated by tools/unverified.py. Do not edit this file directly. -->

Generated list of decomp functions that main-source Kotlin marks `Transcribed from <file>: <Func>`:
written from the decomp but not covered by a `@VerifiesPort` test. Each row carries the reason
given in the KDoc `(not verified: ...)`. Regenerate with `python3 tools/unverified.py --write`;
CI runs `--check`, which also fails when an entry has no `(not verified: ...)` reason.
"""


def _strip_comment(line: str) -> str:
    s = line.strip()
    for prefix in ("/**", "/*", "//", "*"):
        if s.startswith(prefix):
            s = s[len(prefix):]
            break
    if s.endswith("*/"):
        s = s[:-2]
    return s.strip()


def _reason(text: str) -> str | None:
    m = REASON_RX.search(text)
    if not m:
        return None
    depth = 0
    for i in range(m.end(), len(text)):
        c = text[i]
        if c == "(":
            depth += 1
        elif c == ")":
            if depth == 0:
                return " ".join(text[m.end():i].split())
            depth -= 1
    return " ".join(text[m.end():].split())


def parse_file(path: Path, root: Path) -> list[dict]:
    lines = path.read_text(encoding="utf-8").splitlines()
    rel = path.relative_to(root).as_posix()
    entries = []
    for i, line in enumerate(lines):
        for m in TRANSCRIBED_RX.finditer(line):
            rest = line[m.end():]
            parts = [rest.split("*/")[0]]
            closed = "*/" in rest
            j = i + 1
            while not closed and j < len(lines):
                raw = lines[j].strip()
                s = _strip_comment(lines[j])
                if not raw.startswith(("*", "//")) or not s or s.startswith("@"):
                    break
                parts.append(s)
                closed = raw.endswith("*/")
                j += 1
            text = " ".join(parts)
            cut = MARKER_RX.search(text)
            if cut:
                text = text[:cut.start()]
            names = []
            for part in m.group(2).split(","):
                toks = part.split()
                if not toks:
                    continue
                if len(toks) > 1:  # prose starts here, not another name
                    if not names:
                        names.append(toks[0])
                    break
                names.append(toks[0])
            for name in names:
                entries.append({"file": m.group(1), "name": name, "kotlin": rel,
                                "line": i + 1, "reason": _reason(text)})
    return entries


def scan(root: Path) -> list[dict]:
    out = []
    for p in sorted(progress.kotlin_files("main", root)):
        out.extend(parse_file(p, root))
    return out


def render(entries: list[dict]) -> str:
    by_file: dict[str, list[dict]] = defaultdict(list)
    for e in entries:
        by_file[e["file"]].append(e)
    missing = sum(1 for e in entries if e["reason"] is None)
    out = [HEADER, f"Total entries: {len(entries)} across {len(by_file)} decomp files "
                   f"(missing reason: {missing}).\n"]
    for f, es in sorted(by_file.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        out.append(f"## {f} ({len(es)})\n")
        out.append("| Function | Kotlin file | Reason |")
        out.append("| --- | --- | --- |")
        for e in sorted(es, key=lambda e: (e["kotlin"], e["line"], e["name"])):
            reason = (e["reason"] if e["reason"] is not None else "MISSING").replace("|", "\\|")
            out.append(f"| `{e['name']}` | `{e['kotlin']}` | {reason} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write docs/plans/UNVERIFIED.md")
    mode.add_argument("--check", action="store_true", help="check it is current (default)")
    ap.add_argument("--root", type=Path, default=ROOT, help="repository root")
    args = ap.parse_args(argv)
    root = args.root
    entries = scan(root)
    try:
        ref = progress.load_reference(root)
    except OSError:
        ref = {}
    per_system: dict[str, int] = defaultdict(int)
    unknown = []
    for e in entries:
        if e["name"] in ref:
            per_system[ref[e["name"]]["system"]] += 1
        elif ref:
            unknown.append(f"{e['file']}: {e['name']}")
    missing = [e for e in entries if e["reason"] is None]
    print(f"Unverified (Transcribed) entries: {len(entries)}")
    for s, n in sorted(per_system.items(), key=lambda kv: (-kv[1], kv[0])):
        print(f"  {s}: {n}")
    print(f"not-in-decomp-list: {len(unknown)}")
    for u in unknown:
        print(f"  {u}")
    print(f"missing-reason: {len(missing)}")
    for e in missing:
        print(f"  {e['kotlin']}:{e['line']} {e['file']}: {e['name']}")
    expected = render(entries)
    target = root / OUT
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")
        return 0
    stale = not target.is_file() or target.read_text(encoding="utf-8") != expected
    if stale:
        print(f"Out-of-date {OUT}; run python3 tools/unverified.py --write", file=sys.stderr)
    if missing:
        print("Entries without `(not verified: <reason>)` found", file=sys.stderr)
    return 1 if stale or missing else 0


if __name__ == "__main__":
    sys.exit(main())
