#!/usr/bin/env python3
"""List every place main-source Kotlin marks a placeholder with the word "stand-in" in a comment.

Scans main-source Kotlin (same source sets as tools/progress.py) for `stand-in` / `standin` /
`stand in` (case-insensitive) inside comments only (not string literals or identifiers) and
generates docs/plans/STANDINS.md, grouped by the plan row or milestone named in the same comment
(`unassigned` when none). A WIRE task reads it to see what it must replace.

  python3 tools/standins.py --write   regenerate docs/plans/STANDINS.md
  python3 tools/standins.py --check   fail (exit 1) if it is stale (unassigned entries are allowed)
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import progress  # noqa: E402

ROOT = progress.ROOT
OUT = "docs/plans/STANDINS.md"
MATCH_RX = re.compile(r"\bstand[- ]?ins?\b", re.IGNORECASE)
REF_RX = re.compile(r"\b(M6-[A-J]|M7(?:-\d+)?|D\d{2}-[a-z0-9-]+|PP-\d+|CAP-[a-z0-9]+)\b")
DECL_RX = re.compile(r"\b(?:fun|val|var|class|object|interface)\s+(?:<[^>]*>\s*)?(?:[\w.]+\.)?(\w+)")
CHAR_RX = re.compile(r"'(?:\\[^']*|[^'\\])'")
SENTENCE_SPLIT_RX = re.compile(r"(?<=[.!?])\s+(?=[A-Z`\[(\"'])")
ROADMAP_ORDER = [f"M6-{c}" for c in "ABCDEFGHIJ"] + ["M7"]
MAX_LEN = 200
UNASSIGNED = "unassigned"
HEADER = """\
# Stand-ins

<!-- Generated by tools/standins.py. Do not edit this file directly. -->

Generated list of places where main-source Kotlin replaces original behaviour with a placeholder:
every comment or KDoc that says "stand-in". A WIRE task (see ROADMAP "Task rules") replaces the
stand-ins of its milestone with the real port. Each entry names the Kotlin file, the declaration
the comment belongs to (the next declaration for a KDoc or leading comment, else the enclosing
one, else `-`) and the comment sentence. The plan reference is a row id or milestone found in the
same comment; `unassigned` means the comment names none. Regenerate with
`python3 tools/standins.py --write`; CI runs `--check`. Do not edit by hand.
"""


def comments(text: str) -> list[tuple[int, int, str, bool]]:
    """(first line, last line, comment text, trailing) per comment; strings and chars are skipped.

    Line numbers are 0-based. Comment text has its delimiters removed. `trailing` is true when
    code precedes the comment on its first line.
    """
    out: list[tuple[int, int, str, bool]] = []
    n = len(text)
    i = line = line_start = 0
    stack: list[list] = [["code", 0]]  # ["code", brace depth] | ["str"] | ["raw"]
    while i < n:
        c = text[i]
        top = stack[-1]
        if c == "\n":
            line += 1
            line_start = i + 1
            i += 1
        elif top[0] == "str":
            if c == "\\":
                i += 2
            elif c == '"':
                stack.pop()
                i += 1
            elif text.startswith("${", i):
                stack.append(["code", 0])
                i += 2
            else:
                i += 1
        elif top[0] == "raw":
            if text.startswith('"""', i):
                while text.startswith('"', i):  # extra quotes belong to the string
                    i += 1
                stack.pop()
            elif text.startswith("${", i):
                stack.append(["code", 0])
                i += 2
            else:
                i += 1
        elif text.startswith("//", i):
            end = text.find("\n", i)
            end = n if end < 0 else end
            out.append((line, line, text[i + 2:end], bool(text[line_start:i].strip())))
            i = end
        elif text.startswith("/*", i):
            first, trailing, depth, j = line, bool(text[line_start:i].strip()), 1, i + 2
            while j < n and depth:
                if text.startswith("/*", j):
                    depth += 1
                    j += 2
                elif text.startswith("*/", j):
                    depth -= 1
                    j += 2
                else:
                    if text[j] == "\n":
                        line += 1
                        line_start = j + 1
                    j += 1
            out.append((first, line, text[i + 2:max(i + 2, j - 2)], trailing))
            i = j
        elif text.startswith('"""', i):
            stack.append(["raw"])
            i += 3
        elif c == '"':
            stack.append(["str"])
            i += 1
        elif c == "'":
            m = CHAR_RX.match(text, i)
            i = m.end() if m else i + 1
        else:
            if c == "{" and len(stack) > 1:
                top[1] += 1
            elif c == "}" and len(stack) > 1:
                if top[1] == 0:
                    stack.pop()
                else:
                    top[1] -= 1
            i += 1
    return out


def _clean(raw: str) -> str:
    """Comment text without KDoc/`//` decoration, whitespace collapsed."""
    lines = []
    for s in raw.split("\n"):
        s = s.strip()
        while s.startswith("*"):
            s = s[1:].lstrip()
        lines.append(s)
    return " ".join(" ".join(lines).split())


def _sentence(text: str, pos: int) -> str:
    start = 0
    end = len(text)
    for m in SENTENCE_SPLIT_RX.finditer(text):
        if m.end() <= pos:
            start = m.end()
        elif m.start() >= pos:
            end = m.start()
            break
    s = text[start:end].strip()
    if len(s) > MAX_LEN:
        s = s[:MAX_LEN - 3].rstrip() + "..."
    return s


def _declaration(lines: list[str], first: int, last: int, trailing: bool) -> str:
    """Next declaration for a leading comment, else the enclosing preceding one, else `-`."""
    if not trailing:
        for k in range(last + 1, len(lines)):
            s = lines[k].strip()
            if not s or s.startswith("@"):
                continue
            if s.startswith(("//", "/*", "*")):
                continue
            m = DECL_RX.search(s)
            if m:
                return m.group(1)
            break
    indent = len(lines[first]) - len(lines[first].lstrip()) if not trailing else len(lines[first])
    for k in range(first - 1 if not trailing else first, -1, -1):
        s = lines[k]
        if not s.strip() or s.lstrip().startswith(("//", "/*", "*")):
            continue
        ind = len(s) - len(s.lstrip())
        if ind >= indent and not trailing:
            continue
        m = DECL_RX.search(s)
        if m and (trailing or ind < indent):
            return m.group(1)
    return "-"


def parse_file(path: Path, root: Path) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    rel = path.relative_to(root).as_posix()
    # Join consecutive standalone `//` lines (same indent) into one comment block.
    blocks: list[list] = []
    for first, last, raw, trailing in comments(text):
        is_line = first == last and text.split("\n")[first].lstrip().startswith("//") and not trailing
        if (is_line and blocks and blocks[-1][4] and blocks[-1][1] == first - 1):
            blocks[-1][1] = last
            blocks[-1][2] += "\n" + raw
        else:
            blocks.append([first, last, raw, trailing, is_line])
    entries = []
    for first, last, raw, trailing, _ in blocks:
        cleaned = _clean(raw)
        ref = REF_RX.search(cleaned)
        for m in MATCH_RX.finditer(cleaned):
            entries.append({"file": rel, "decl": _declaration(lines, first, last, trailing),
                            "text": _sentence(cleaned, m.start()), "ref": ref.group(1) if ref else UNASSIGNED})
    return entries


def scan(root: Path) -> list[dict]:
    seen: set[tuple[str, str, str]] = set()
    out = []
    for p in sorted(progress.kotlin_files("main", root)):
        for e in parse_file(p, root):
            key = (e["file"], e["decl"], e["text"])
            if key not in seen:
                seen.add(key)
                out.append(e)
    return out


def _ref_key(ref: str) -> tuple[int, int, str]:
    if ref == UNASSIGNED:
        return (3, 0, ref)
    if ref in ROADMAP_ORDER:
        return (0, ROADMAP_ORDER.index(ref), ref)
    if ref.startswith("M7-"):
        return (0, len(ROADMAP_ORDER), ref)
    return (1, 0, ref)


def render(entries: list[dict]) -> str:
    by_ref: dict[str, list[dict]] = defaultdict(list)
    for e in entries:
        by_ref[e["ref"]].append(e)
    refs = sorted(by_ref, key=_ref_key)
    out = [HEADER, f"Total entries: {len(entries)} across {len(set(e['file'] for e in entries))} Kotlin files.\n"]
    out.append("| Plan reference | Entries |")
    out.append("| --- | --- |")
    for r in refs:
        out.append(f"| {r} | {len(by_ref[r])} |")
    out.append("")
    for r in refs:
        out.append(f"## {r} ({len(by_ref[r])})\n")
        out.append("| Kotlin file | Declaration | Stand-in |")
        out.append("| --- | --- | --- |")
        for e in sorted(by_ref[r], key=lambda e: (e["file"], e["decl"], e["text"])):
            text = e["text"].replace("|", "\\|")
            out.append(f"| `{e['file']}` | `{e['decl']}` | {text} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write docs/plans/STANDINS.md")
    mode.add_argument("--check", action="store_true", help="check it is current (default)")
    ap.add_argument("--root", type=Path, default=ROOT, help="repository root")
    args = ap.parse_args(argv)
    root = args.root
    entries = scan(root)
    per_ref: dict[str, int] = defaultdict(int)
    for e in entries:
        per_ref[e["ref"]] += 1
    print(f"Stand-in entries: {len(entries)}")
    for r in sorted(per_ref, key=_ref_key):
        print(f"  {r}: {per_ref[r]}")
    print(f"unassigned: {per_ref.get(UNASSIGNED, 0)}")
    expected = render(entries)
    target = root / OUT
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")
        return 0
    if not target.is_file() or target.read_text(encoding="utf-8") != expected:
        print(f"Out-of-date {OUT}; run python3 tools/standins.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
