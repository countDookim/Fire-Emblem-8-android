#!/usr/bin/env python3
"""Compute porting progress, regenerate the README progress block and docs/port_map.json.

A decomp function counts as **ported** only when BOTH hold:
  1. some main-source Kotlin KDoc says  `Ported from <file>: <Function>`  (exact decomp name), and
  2. a test annotated  `@VerifiesPort("<Function>", ...)`  PASSED in the JUnit XML results
     (skipped tests -- e.g. differential tests without reference data -- do not count).

Functions with (1) but not (2) are reported as "implemented, unverified" and never counted.
Mentions of `Partially ported from ...` are ignored entirely.

    python3 tools/progress.py            # print summary (uses existing build/test-results)
    python3 tools/progress.py --write    # also rewrite README.md block + docs/port_map.json

The denominator is reference/decomp_functions.tsv (generated by tools/gen_reference.py, committed).
Self-test (fixture repo, also run in CI): python3 -m unittest discover tools/tests
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PORTED_RX = re.compile(r"(?<![Pp]artially )Ported from (src/[\w./-]+|asm/[\w./-]+): ([\w, ]+)")
VERIFIES_RX = re.compile(r"@VerifiesPort\(([^)]*)\)")
FUN_RX = re.compile(r"\bfun\s+(`[^`]+`|\w+)\s*\(")
CLASS_RX = re.compile(r"^\s*(?:\w+\s+)*(?:class|object)\s+(\w+)", re.M)
PKG_RX = re.compile(r"^package\s+([\w.]+)", re.M)
START, END = "<!-- progress:start -->", "<!-- progress:end -->"
BAR_WIDTH = 20


def load_reference(root: Path = ROOT) -> dict[str, dict]:
    with open(root / "reference" / "decomp_functions.tsv") as f:
        return {r["name"]: r for r in csv.DictReader(f, delimiter="\t")}


# Source-set dirs per kind: plain JVM modules use main/test, Kotlin Multiplatform ones (ADR 0013)
# commonMain/jvmMain and jvmTest.
SOURCE_SETS = {"main": ("main", "commonMain", "jvmMain"), "test": ("test", "jvmTest")}


def kotlin_files(kind: str, root: Path = ROOT) -> list[Path]:
    return [p for k in SOURCE_SETS.get(kind, (kind,)) for p in root.glob(f"**/src/{k}/kotlin/**/*.kt")
            if "/build/" not in p.relative_to(root).as_posix()]


def find_ported(ref: dict[str, dict], root: Path = ROOT) -> tuple[dict[str, str], list[str]]:
    ported, unknown = {}, []
    for p in kotlin_files("main", root):
        for m in PORTED_RX.finditer(p.read_text()):
            for name in (n.strip() for n in m.group(2).split(",")):
                if not name:
                    continue
                if name in ref:
                    ported.setdefault(name, p.relative_to(root).as_posix())
                else:
                    unknown.append(f"{p.relative_to(root)}: {name}")
    return ported, unknown


def find_verifying_tests(root: Path = ROOT) -> dict[tuple[str, str], list[str]]:
    """(fully-qualified class, method) -> decomp function names it verifies."""
    out = {}
    for p in kotlin_files("test", root):
        text = p.read_text()
        pkg = (PKG_RX.search(text) or [None, ""])[1]
        for m in VERIFIES_RX.finditer(text):
            names = re.findall(r'"(\w+)"', m.group(1))
            fm = FUN_RX.search(text, m.end())
            if not fm:
                continue
            cls = None
            for cm in CLASS_RX.finditer(text, 0, m.start()):
                cls = cm.group(1)
            method = fm.group(1).strip("`")
            out[(f"{pkg}.{cls}" if pkg else cls, method)] = names
    return out


def passed_tests(root: Path = ROOT) -> set[tuple[str, str]]:
    ok = set()
    for x in root.glob("**/build/test-results/**/*.xml"):
        try:
            tree = ET.parse(x)
        except ET.ParseError:
            continue
        for tc in tree.iter("testcase"):
            if any(child.tag in ("failure", "error", "skipped") for child in tc):
                continue
            ok.add((tc.get("classname", ""), re.sub(r"\(.*\)$", "", tc.get("name", ""))))
    return ok


def bar(done: int, total: int) -> str:
    frac = done / total if total else 0.0
    filled = int(frac * BAR_WIDTH)  # floor: the bar never shows more than is done
    return "█" * filled + "░" * (BAR_WIDTH - filled)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="rewrite README.md and docs/port_map.json")
    ap.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)  # tools/tests fixtures
    args = ap.parse_args(argv)
    root: Path = args.root

    ref = load_reference(root)
    ported, unknown = find_ported(ref, root)
    tests = find_verifying_tests(root)
    passed = passed_tests(root)
    verified_by: dict[str, list[str]] = defaultdict(list)
    for (cls, method), names in tests.items():
        if (cls, method) in passed:
            for n in names:
                verified_by[n].append(f"{cls}#{method}")

    done = sorted(n for n in ported if verified_by.get(n))
    pending = sorted(n for n in ported if not verified_by.get(n))
    total = len(ref)
    pct = 100.0 * len(done) / total if total else 0.0

    per_sys: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])
    for name, r in ref.items():
        s = per_sys[r["system"]]
        s[0] += 1
        if name in ported:
            s[2] += 1
        if name in done:
            s[1] += 1

    pct_str = f"{pct:.2f}" if 0 < pct < 1 else f"{pct:.0f}"
    lines = [
        START,
        f"**Progress (estimate):** `{bar(len(done), total)} {pct_str}% ({len(done)} / {total} functions)`",
        "",
        f"<sub>Estimate = decomp functions ported to Kotlin **and** covered by a passing verifying test, "
        f"over all {total} functions in the pinned decomp. Implemented but not yet verified: {len(pending)}. "
        f"Generated by `tools/progress.py`; never edited by hand.</sub>",
        "",
        "| System | Verified | Implemented | Functions | % |",
        "|---|---:|---:|---:|---:|",
    ]
    for sysname, (tot, ver, imp) in sorted(per_sys.items(), key=lambda kv: -kv[1][0]):
        lines.append(f"| {sysname} | {ver} | {imp} | {tot} | {100.0 * ver / tot:.1f} |")
    lines.append(END)
    block = "\n".join(lines)

    print(lines[1])
    print(f"verified: {', '.join(done) or '-'}")
    if pending:
        print(f"implemented, unverified: {', '.join(pending)}")
    if not passed:
        print("note: no JUnit results found (run ./gradlew jvmTest first); nothing counts as verified", file=sys.stderr)
    if unknown:
        print("WARNING: 'Ported from' names not in reference list:\n  " + "\n  ".join(unknown), file=sys.stderr)

    if args.write:
        readme = root / "README.md"
        text = readme.read_text()
        if START in text and END in text:
            text = text[: text.index(START)] + block + text[text.index(END) + len(END):]
        else:
            text = block + "\n\n" + text
        readme.write_text(text)
        port_map = {
            "generated_by": "tools/progress.py",
            "decomp": (root / "reference" / "DECOMP_VERSION").read_text().split(),
            "summary": {"total": total, "verified": len(done), "implemented_unverified": len(pending)},
            "functions": {
                n: {
                    "decomp_file": ref[n]["file"],
                    "system": ref[n]["system"],
                    "kotlin_file": ported[n],
                    "status": "verified" if n in done else "implemented",
                    "tests": sorted(verified_by.get(n, [])),
                }
                for n in sorted(ported)
            },
        }
        (root / "docs").mkdir(exist_ok=True)
        (root / "docs" / "port_map.json").write_text(json.dumps(port_map, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
