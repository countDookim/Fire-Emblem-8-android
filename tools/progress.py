#!/usr/bin/env python3
"""Compute porting progress, regenerate the README progress block and docs/port_map.json.

A decomp function counts as **ported** only when BOTH hold:
  1. some main-source Kotlin KDoc says  `Ported from <file>: <Function>`  (exact decomp name), and
  2. a test annotated  `@VerifiesPort("<Function>", ...)`  PASSED in the JUnit XML results
     (skipped tests -- e.g. differential tests without reference data -- do not count).

Functions with (1) but not (2) are reported as "implemented, unverified" and never counted.
Mentions of `Partially ported from ...` are ignored entirely.

    python3 tools/progress.py            # print summary (uses existing build/test-results)
    python3 tools/progress.py --write    # also rewrite README.md block + docs/port_map.json

The denominator is reference/decomp_functions.tsv (generated by tools/gen_reference.py, committed)
minus the out-of-scope functions (link-cable play, debug menus; see OUT_OF_SCOPE_FILES below).
Self-test (fixture repo, also run in CI): python3 -m unittest discover tools/tests
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PORTED_RX = re.compile(r"(?<![Pp]artially )Ported from (src/[\w./-]+|asm/[\w./-]+): ([\w, ]+)")
VERIFIES_RX = re.compile(r"@VerifiesPort\(([^)]*)\)")
FUN_RX = re.compile(r"\bfun\s+(`[^`]+`|\w+)\s*\(")
CLASS_RX = re.compile(r"^\s*(?:\w+\s+)*(?:class|object)\s+(\w+)", re.M)
PKG_RX = re.compile(r"^package\s+([\w.]+)", re.M)
START, END = "<!-- progress:start -->", "<!-- progress:end -->"
BAR_WIDTH = 20

# Owner decision 2026-11-11 (docs/plans/ROADMAP.md "Owner decisions"): link-cable play and the debug
# menus are OUT OF SCOPE for the progress percentage; they are reported separately, never counted.
# A function is out of scope when its decomp file is listed here or belongs to system `link`
# (every src/sio_*.c plus src/sioerror.c), unless it is named in KEEP_IN_SCOPE.
OUT_OF_SCOPE_FILES = frozenset({
    "src/uidebug.c",
    "src/bmdebug.c",
    "src/bmcommanddbg.c",
    "src/mapanim_debug.c",
})
OUT_OF_SCOPE_SYSTEMS = frozenset({"link"})
# Out-of-scope-file functions that retail (in-scope) code still references, so they stay in scope.
# Found by tools/check_scope_callers.py; each entry names the referencing file.
KEEP_IN_SCOPE: frozenset[str] = frozenset({
    "AreAnyEnemyUnitDead",  # src/uidebug.c, called by src/bmtrick.c and src/eventinfo.c (chapter goals)
    "Get8",  # src/bmdebug.c, menu override in src/eventscr.c
    "CheckInLinkArena",  # src/sio_main.c, guard called by src/prep*.c, src/phasechangefx.c, src/unitlistscreen.c
    "SioStrCpy",  # src/sio_main.c, called by src/bmsave-multiarena.c
    "sub_8042EA8",  # src/sio_main.c, called by src/prep_atmenu.c
    "CallEraseSaveEvent",  # src/sio_event.c, PROC_CALL in src/gamecontrol.c
    "StartLinkArenaMainMenu",  # src/sio_menu.c, PROC_CALL in src/gamecontrol.c
    "LoadLinkArenaFogPlaceholder",  # src/sio_battlemap.c, called by src/banim-ekrbattleending.c
})
# Not kept: the ~30 Debug*/EndMenuAndClear functions of src/bmdebug.c are referenced only from the debug
# MenuDef tables in src/menu_def.c (gDebugMenuDef & co.), i.e. the debug menus themselves.


def is_out_of_scope(name: str, row: dict) -> bool:
    if name in KEEP_IN_SCOPE:
        return False
    f = row["file"]
    return f in OUT_OF_SCOPE_FILES or f.startswith("src/sio_") or row["system"] in OUT_OF_SCOPE_SYSTEMS


def load_reference(root: Path = ROOT) -> dict[str, dict]:
    with open(root / "reference" / "decomp_functions.tsv") as f:
        return {r["name"]: r for r in csv.DictReader(f, delimiter="\t")}


# Source-set dirs per kind: plain JVM modules use main/test, Kotlin Multiplatform ones (ADR 0013)
# commonMain/jvmMain and jvmTest.
SOURCE_SETS = {"main": ("main", "commonMain", "jvmMain"), "test": ("test", "jvmTest")}


def kotlin_files(kind: str, root: Path = ROOT) -> list[Path]:
    # Skips build output and agent worktrees under .claude/ (other checkouts of the repo).
    return [p for k in SOURCE_SETS.get(kind, (kind,)) for p in root.glob(f"**/src/{k}/kotlin/**/*.kt")
            if "/build/" not in p.relative_to(root).as_posix()
            and not p.relative_to(root).as_posix().startswith(".claude/")]


def find_ported(ref: dict[str, dict], root: Path = ROOT) -> tuple[dict[str, str], list[str]]:
    ported, unknown = {}, []
    for p in kotlin_files("main", root):
        for m in PORTED_RX.finditer(p.read_text()):
            for name in (n.strip() for n in m.group(2).split(",")):
                if not name:
                    continue
                if name in ref:
                    ported.setdefault(name, p.relative_to(root).as_posix())
                else:
                    unknown.append(f"{p.relative_to(root)}: {name}")
    return ported, unknown


def unknown_verifies_names(tests: dict[tuple[str, str], list[str]], ref: dict[str, dict]) -> list[str]:
    """`@VerifiesPort` names (as `Class#method: name`) that match no decomp function; they count for nothing."""
    return sorted(f"{cls}#{method}: {n}" for (cls, method), names in tests.items() for n in names if n not in ref)


def find_verifying_tests(root: Path = ROOT) -> dict[tuple[str, str], list[str]]:
    """(fully-qualified class, method) -> decomp function names it verifies."""
    out = {}
    for p in kotlin_files("test", root):
        text = p.read_text()
        pkg = (PKG_RX.search(text) or [None, ""])[1]
        for m in VERIFIES_RX.finditer(text):
            names = re.findall(r'"([^"]+)"', m.group(1))  # any quoted string, so bad names surface
            fm = FUN_RX.search(text, m.end())
            if not fm:
                continue
            cls = None
            for cm in CLASS_RX.finditer(text, 0, m.start()):
                cls = cm.group(1)
            method = fm.group(1).strip("`")
            out[(f"{pkg}.{cls}" if pkg else cls, method)] = names
    return out


def passed_tests(root: Path = ROOT) -> set[tuple[str, str]]:
    ok = set()
    for x in root.glob("**/build/test-results/**/*.xml"):
        if x.relative_to(root).as_posix().startswith(".claude/"):
            continue  # agent worktrees hold other checkouts' results
        try:
            tree = ET.parse(x)
        except ET.ParseError:
            continue
        for tc in tree.iter("testcase"):
            if any(child.tag in ("failure", "error", "skipped") for child in tc):
                continue
            ok.add((tc.get("classname", ""), re.sub(r"\(.*\)(\[\w+\])?$", "", tc.get("name", ""))))
    return ok


def bar(done: int, total: int) -> str:
    frac = done / total if total else 0.0
    filled = int(frac * BAR_WIDTH)  # floor: the bar never shows more than is done
    return "█" * filled + "░" * (BAR_WIDTH - filled)


def pct_text(done: int, total: int) -> str:
    """Percentage for the README line, floored (never rounded up): one decimal, two below 1%."""
    if not total or not done:
        return "0"
    if 100 * done < total:
        return f"{10000 * done // total / 100:.2f}"
    tenths = 1000 * done // total
    return f"{tenths // 10}" if tenths % 10 == 0 else f"{tenths / 10:.1f}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="rewrite README.md and docs/port_map.json")
    ap.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)  # tools/tests fixtures
    args = ap.parse_args(argv)
    root: Path = args.root

    ref = load_reference(root)
    ported, unknown = find_ported(ref, root)
    tests = find_verifying_tests(root)
    passed = passed_tests(root)
    verified_by: dict[str, list[str]] = defaultdict(list)
    for (cls, method), names in tests.items():
        if (cls, method) in passed:
            for n in names:
                verified_by[n].append(f"{cls}#{method}")

    out_of_scope = {n for n, r in ref.items() if is_out_of_scope(n, r)}
    all_done = sorted(n for n in ported if verified_by.get(n))
    done = [n for n in all_done if n not in out_of_scope]  # counted in the percentage
    done_oos = [n for n in all_done if n in out_of_scope]  # verified but never counted
    pending = sorted(n for n in ported if not verified_by.get(n))
    total = len(ref)
    in_scope_total = total - len(out_of_scope)

    per_sys: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])
    oos_row = [0, 0, 0]  # total, verified, implemented
    for name, r in ref.items():
        s = oos_row if name in out_of_scope else per_sys[r["system"]]
        s[0] += 1
        if name in ported:
            s[2] += 1
        if name in all_done:
            s[1] += 1

    pct_str = pct_text(len(done), in_scope_total)
    lines = [
        START,
        f"**Progress (estimate):** `{bar(len(done), in_scope_total)} {pct_str}% "
        f"({len(done)} / {in_scope_total} functions in scope)`",
        "",
        f"<sub>Estimate = decomp functions ported to Kotlin **and** covered by a passing verifying test, "
        f"over the {in_scope_total} in-scope functions of the pinned decomp. {len(out_of_scope)} functions "
        f"(link-cable play, debug menus) are out of scope and not counted. "
        f"Implemented but not yet verified: {len(pending)}. "
        f"Generated by `tools/progress.py`; never edited by hand.</sub>",
        "",
        "| System | Verified | Implemented | Functions | % |",
        "|---|---:|---:|---:|---:|",
    ]
    for sysname, (tot, ver, imp) in sorted(per_sys.items(), key=lambda kv: -kv[1][0]):
        if tot:
            lines.append(f"| {sysname} | {ver} | {imp} | {tot} | {100.0 * ver / tot:.1f} |")
    lines.append(f"| out of scope (link, debug menus) | {oos_row[1]} | {oos_row[2]} | {oos_row[0]} | |")
    lines.append(END)
    block = "\n".join(lines)

    print(lines[1])
    print(f"verified: {', '.join(done) or '-'}")
    if done_oos:
        print(f"out-of-scope verified (not counted): {', '.join(done_oos)}")
    if pending:
        print(f"implemented, unverified: {', '.join(pending)}")
    # "Ported from" names no @VerifiesPort test names: their KDoc must say "Transcribed from ...
    # (not verified: ...)" instead (CLAUDE.md rule 4, ADR 0006). Should stay 0.
    tagged = {n for names in tests.values() for n in names}
    print(f"ported-without-tag: {sum(1 for n in ported if n not in tagged)}")
    # @VerifiesPort names that match no decomp function (e.g. "src/x.c: F") silently count for nothing.
    bad = unknown_verifies_names(tests, ref)
    print(f"unknown-verifies-names: {len(bad)}")
    for b in bad:
        print(f"  {b}")
    if not passed:
        print("note: no JUnit results found (run ./gradlew jvmTest first); nothing counts as verified", file=sys.stderr)
    if unknown:
        print("WARNING: 'Ported from' names not in reference list:\n  " + "\n  ".join(unknown), file=sys.stderr)

    if args.write:
        readme = root / "README.md"
        text = readme.read_text()
        if START in text and END in text:
            text = text[: text.index(START)] + block + text[text.index(END) + len(END):]
        else:
            text = block + "\n\n" + text
        readme.write_text(text)
        port_map = {
            "generated_by": "tools/progress.py",
            "decomp": (root / "reference" / "DECOMP_VERSION").read_text().split(),
            "summary": {
                "total": total,
                "in_scope_total": in_scope_total,
                "out_of_scope": len(out_of_scope),
                "verified": len(done),
                "implemented_unverified": len(pending),
            },
            "functions": {
                n: {
                    "decomp_file": ref[n]["file"],
                    "system": ref[n]["system"],
                    "in_scope": n not in out_of_scope,
                    "kotlin_file": ported[n],
                    "status": "verified" if n in all_done else "implemented",
                    "tests": sorted(verified_by.get(n, [])),
                }
                for n in sorted(ported)
            },
        }
        (root / "docs").mkdir(exist_ok=True)
        (root / "docs" / "port_map.json").write_text(json.dumps(port_map, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
