package fe8.game.bm

import fe8.game.bm.StructCodec.s8
import fe8.game.bm.StructCodec.u16
import fe8.game.bm.StructCodec.u32
import fe8.game.bm.StructCodec.u8
import gbafe.core.rng.RngService
import gbafe.proc.Proc
import gbafe.proc.ProcBoolFunc
import gbafe.proc.ProcEngine
import gbafe.proc.ProcFunc
import gbafe.proc.ProcScript
import gbafe.proc.ProcScripts.call
import gbafe.proc.ProcScripts.call2
import gbafe.proc.ProcScripts.end
import gbafe.proc.ProcScripts.goto
import gbafe.proc.ProcScripts.label
import gbafe.proc.ProcScripts.sleep
import gbafe.proc.ProcScripts.whileTrue

/**
 * The combat action of src/bmmind.c: what the player phase runs after A on an attack target
 * (`ApplyUnitAction`'s combat branch, [actionCombat]), the proc [script]
 * (`sProcScr_CombatAction`) and its steps, and [storeRNStateToActionStruct].
 *
 * The battle is generated by [BattleGenerate.battleGenerateReal] at once; the proc then plays the
 * map battle animation ([Hooks.beginBattleAnimations], M6-H), writes the battle
 * units back into the unit table ([BmBattle.battleApplyGameStateUpdates], MC-15) and handles an
 * item drop and the deaths. The units are written back once, after the animation, as in the game.
 *
 * Animations are always the map animations here (Options "Animation Off" sets
 * `BATTLE_CONFIG_MAPANIMS` in the original), so the script always takes label 1 after the
 * animation; `BATTLE_PostCombatDeathFades` and `BATTLE_DeleteLinkedMOVEUNIT` (the animations-on
 * death fade) are not written and fail loudly if the script ever reaches them. The map
 * animation's own writes (BG, OAM and palettes, the unit sprites, the hit flash, the death fade)
 * are M6-H and are not compared by the test.
 *
 * Not written (no capture runs them; they fail loudly): the Nightmare staff, a wall or trap
 * target (`InitObstacleBattleUnit`), the ballista (`BattleGenerateBallistaReal`).
 *
 * @param engine the proc engine the proc runs on.
 * @param battle the battle units and stats, and the write-back into the unit table.
 * @param generate the real battle generation.
 * @param units the unit table.
 * @param active `gActionData` (the subject, target and weapon slot) and `gActiveUnit`.
 */
public class CombatAction(
    private val engine: ProcEngine,
    private val battle: BmBattle,
    private val generate: BattleGenerate,
    private val units: UnitTable,
    private val active: ActiveUnit,
) {
    /** `GetBattleAnimPreconfType`. */
    public fun interface PreconfType {
        /** The animation type (`PLAY_ANIMCONF_*`). */
        public fun get(): Int
    }

    /** `DropRescueOnDeath(proc, unit)`. */
    public fun interface RescueDrop {
        /** Drops the unit [unit] (an id) rescued by a unit that died. */
        public fun drop(proc: Proc, unit: Int)
    }

    /** `KillUnitOnCombatDeath(unitA, unitB)`. */
    public fun interface UnitKiller {
        /** Kills unit [unit] when its HP is 0; [killer] is the other unit of the battle. */
        public fun kill(unit: Int, killer: Int)
    }

    /** `NewPopup_GeneralItemGot(unit, item, proc)`. */
    public fun interface ItemPopup {
        /** Shows the "got item" popup for [unit] and blocks [proc] until it ends. */
        public fun start(unit: Int, item: Int, proc: Proc)
    }

    /** Services outside the ported file; each hook names the row that replaces it. */
    public class Hooks {
        /**
         * `BeginBattleAnimations` (bmbattle.c): starts the map battle animation and sets
         * `BATTLE_CONFIG_MAPANIMS`. Stand-in until M6-H: sets only the flag, so the animation
         * ends at once.
         */
        public var beginBattleAnimations: ProcFunc = ProcFunc {}

        /**
         * `GetBattleAnimPreconfType` (bmbattle.c). Stand-in until M6-H: always
         * `PLAY_ANIMCONF_OFF` (map animations).
         */
        public var getBattleAnimPreconfType: PreconfType = PreconfType { PLAY_ANIMCONF_OFF }

        /** `DoesBMXFADEExist`. */
        public var doesBmxFadeExist: ProcBoolFunc = ProcBoolFunc { false }

        /**
         * `DropRescueOnDeath` (bmmind.c). Stand-in until MC-16: does nothing, so a unit that
         * dies while rescuing keeps its passenger.
         */
        public var dropRescueOnDeath: RescueDrop = RescueDrop { _, _ -> }

        /**
         * `KillUnitOnCombatDeath` (bmmind.c, with `UnitKill`). Stand-in until MC-16: does
         * nothing, so a unit with 0 HP stays on the map.
         */
        public var killUnitOnCombatDeath: UnitKiller = UnitKiller { _, _ -> }

        /**
         * `NewPopup_GeneralItemGot` (popup.c): the killer is given the dead unit's last item.
         * Stand-in until MC-16 (the drop): nothing is shown or given.
         */
        public var itemGotPopup: ItemPopup = ItemPopup { _, _, _ -> }
    }

    /** The hooks, set by the game. */
    public val hooks: Hooks = Hooks()

    /** `struct CombatActionProc` past `PROC_HEADER`: `unitIdA` (+0x64) and `unitIdB` (+0x66). */
    public class State {
        /** `unitIdA` (s16): the actor's unit id. */
        public var unitIdA: Int = 0

        /** `unitIdB` (s16): the target's unit id. */
        public var unitIdB: Int = 0
    }

    init {
        hooks.beginBattleAnimations = ProcFunc {
            battle.stats.config = battle.stats.config or BattleStats.CONFIG_MAPANIMS
        }
    }

    /**
     * `sProcScr_CombatAction` (0x0859DABC): CALL `BeginBattleAnimations`, SLEEP 1, CALL
     * `BattleApplyGameStateUpdates`, WHILE `DoesBMXFADEExist`, CALL
     * `BATTLE_GOTO1_IfNobodyIsDead`, CALL `BATTLE_PostCombatDeathFades`, SLEEP 32, CALL
     * `BATTLE_DeleteLinkedMOVEUNIT`, LABEL 1, CALL_2 `BATTLE_HandleItemDrop`, CALL
     * `BATTLE_HandleCombatDeaths`, SLEEP 0, END. The two death-fade calls are not written (see
     * the class). A data table, so it has no `Ported from` tag; its command positions are
     * compared with the capture.
     */
    public val script: ProcScript = ProcScript(
        "sProcScr_CombatAction",
        listOf(
            call(ProcFunc { hooks.beginBattleAnimations.invoke(it) }),
            sleep(1),
            call(ProcFunc { battle.battleApplyGameStateUpdates() }),
            whileTrue(ProcBoolFunc { hooks.doesBmxFadeExist.invoke(it) }),
            call(ProcFunc { battleGoto1IfNobodyIsDead(it) }),
            call(ProcFunc { error("BATTLE_PostCombatDeathFades is not written (map anims set)") }),
            sleep(32),
            call(ProcFunc { error("BATTLE_DeleteLinkedMOVEUNIT is not written (map anims set)") }),
            label(1),
            call2(ProcBoolFunc { battleHandleItemDrop(it) }),
            call(ProcFunc { battleHandleCombatDeaths(it) }),
            sleep(0),
            end(),
        ),
        newState = { State() },
    )

    /**
     * Ported from src/bmmind.c: ActionCombat
     *
     * The combat action: clears the actor's item-effect flag, generates the real battle of the
     * subject on the target ([BattleGenerate.battleGenerateReal]) and starts [script] as a child
     * of [proc] that blocks it. Returns false (the caller's `PROC_CALL_2` yields until the child
     * ends). The Nightmare staff, a target without a unit (a wall or trap) and the ballista are
     * transcribed as failing loudly (not verified: no capture has them).
     */
    public fun actionCombat(proc: Proc): Boolean {
        val action = active.action
        val subject = units.unitOffset(action.subjectIndex)
        val target = units.unitOffset(action.targetIndex)
        val item = units.item(action.subjectIndex, action.itemSlotIndex) and 0xFF

        battle.actor.hasItemEffectTarget = 0

        check(item != ITEM_NIGHTMARE) { "ActionCombat: the Nightmare staff is not written" }
        check(target >= 0) { "ActionCombat: InitObstacleBattleUnit is not written" }
        check(action.itemSlotIndex != BmBattle.BU_ISLOT_BALLISTA) {
            "ActionCombat: BattleGenerateBallistaReal is not written"
        }

        generate.battleGenerateReal(units.bytes, subject, target)

        engine.startBlocking(script, proc)

        return false
    }

    /**
     * Ported from src/bmmind.c: BATTLE_GOTO1_IfNobodyIsDead
     *
     * Goes to label 1 (skips the death fades) when the battle was shown with map animations
     * (`BATTLE_CONFIG_MAPANIMS`). Without them (not written) it would go only when neither unit
     * died.
     */
    private fun battleGoto1IfNobodyIsDead(proc: Proc) {
        check((battle.stats.config and BattleStats.CONFIG_MAPANIMS) != 0) {
            "BATTLE_GOTO1_IfNobodyIsDead: animations-on path is not written"
        }
        engine.goto(proc, 1)
    }

    /**
     * Ported from src/bmmind.c: BATTLE_HandleItemDrop
     *
     * Remembers the two units' ids in the proc, then, when a unit died that drops its item
     * (`US_DROP_ITEM`, with an item) to a player-army unit, shows the item popup
     * ([Hooks.itemGotPopup]) and waits (false). Otherwise goes on (true). The drop branch is
     * transcribed (not verified: no capture has a drop).
     */
    private fun battleHandleItemDrop(proc: Proc): Boolean {
        val state = proc.state as State
        val actorId = s8(battle.actor.bytes, OFF_INDEX)
        val targetId = s8(battle.target.bytes, OFF_INDEX)
        state.unitIdA = actorId
        state.unitIdB = targetId

        var dead = 0
        var killer = 0
        if (u8(battle.actor.bytes, OFF_CUR_HP) == 0) {
            dead = actorId
            killer = targetId
        }
        if (u8(battle.target.bytes, OFF_CUR_HP) == 0) {
            dead = targetId
            killer = actorId
        }
        if (dead == 0) return true

        val deadAt = units.unitOffset(dead)
        if ((u32(units.bytes, deadAt + OFF_STATE) and US_DROP_ITEM) == 0) return true
        if (u16(units.bytes, deadAt + OFF_ITEMS) == 0) return true
        if ((s8(units.bytes, units.unitOffset(killer) + OFF_INDEX) and 0xC0) != FACTION_BLUE) {
            return true
        }
        var count = 0
        while (count < UnitLoader.UNIT_ITEM_COUNT &&
            u16(units.bytes, deadAt + OFF_ITEMS + 2 * count) != 0
        ) {
            count++
        }
        hooks.itemGotPopup.start(
            killer, u16(units.bytes, deadAt + OFF_ITEMS + 2 * (count - 1)), proc,
        )
        return false
    }

    /**
     * Ported from src/bmmind.c: BATTLE_HandleCombatDeaths
     *
     * For each of the two units (as [battleHandleItemDrop] stored them): drops a rescued unit
     * ([Hooks.dropRescueOnDeath]) when it died, then kills it ([Hooks.killUnitOnCombatDeath]),
     * the actor first.
     */
    private fun battleHandleCombatDeaths(proc: Proc) {
        val state = proc.state as State
        hooks.dropRescueOnDeath.drop(proc, state.unitIdA)
        hooks.dropRescueOnDeath.drop(proc, state.unitIdB)
        hooks.killUnitOnCombatDeath.kill(state.unitIdA, state.unitIdB)
        hooks.killUnitOnCombatDeath.kill(state.unitIdB, state.unitIdA)
    }

    /** [storeRNStateToActionStruct] and the constants. */
    public companion object {
        /**
         * Ported from src/bmmind.c: StoreRNStateToActionStruct
         *
         * Copies the three words of [rng]'s primary state into the first six bytes of the raw
         * `gActionData` [actionData] (its `_u00`).
         */
        public fun storeRNStateToActionStruct(rng: RngService, actionData: ByteArray) {
            for (i in 0 until 3) StructCodec.put16(actionData, i * 2, rng.primary.word(i))
        }

        /** `PLAY_ANIMCONF_OFF`. */
        public const val PLAY_ANIMCONF_OFF: Int = 1

        private const val ITEM_NIGHTMARE = 0xA6
        private const val OFF_INDEX = 0x0B
        private const val OFF_STATE = 0x0C
        private const val OFF_CUR_HP = 0x13
        private const val OFF_ITEMS = 0x1E
        private const val US_DROP_ITEM = 1 shl 12
        private const val FACTION_BLUE = 0x00
    }
}
